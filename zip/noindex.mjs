// 시세 비교 글(apt-*) 검색 제외(noindex) — 2026-11-16 사용자 결정. 되돌리기는 --undo.
// 구글이 사이트 전체를 낮게 평가해 색인이 빠졌고, 같은 틀의 시세 비교 글이 공개 글의 절반이라 색인 대상에서 뺀다. 글·주소는 그대로 둔다.
// Rank Math 글 메타 rank_math_robots만 REST(rankmath/v1/updateMeta)로 바꾼다 — 글 저장(upsert)이 아니라 본문·수정 시각을 건드리지 않고,
// 하루 수정 한도(wp.mjs UPDATE_CAP)·APT_EDIT_HOLD와 무관하다. 성공 판정은 실제 페이지의 <meta name="robots">로 한다.
// node zip/noindex.mjs [--live]                       계획만(쓰기 없음): 대상 편수·목록, --live면 지금 페이지 robots도
// node zip/noindex.mjs --go [--only apt-…,apt-…]      noindex로 바꾸고 페이지로 확인 → 캐시 비우기. 기록 data/zip_noindex.json
// node zip/noindex.mjs --undo [--only apt-…]          index로 되돌리고 확인
// node zip/noindex.mjs --verify                       쓰기 없이 대상 페이지 robots·사이트맵의 apt- 주소 수·deep- 글 3편 확인
// node zip/noindex.mjs --check                        네트워크 없는 자체 점검
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT } from '../tistory/common.mjs';

const FILE = join(ROOT, 'data/zip_noindex.json');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'; // 방화벽이 기본 UA를 막는다
const GAP = 700, STOP = 3;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const kst = () => new Date(Date.now() + 9 * 3600e3).toISOString().slice(0, 16).replace('T', ' ');

export const pick = (posts) => posts.filter((p) => p.slug.startsWith('apt-') && (p.type ?? 'post') === 'post');

// <meta name="robots" content="…"> → 'noindex' | 'index' | null(메타 없음). 「index」는 「noindex」 안에도 있어 낱말 단위로 본다
export function robotsOf(html) {
  for (const tag of html.match(/<meta\b[^>]*>/gi) || []) {
    if (!/\bname\s*=\s*["']robots["']/i.test(tag)) continue;
    const words = (tag.match(/\bcontent\s*=\s*["']([^"']*)["']/i)?.[1] || '').toLowerCase().split(/[\s,]+/);
    return words.includes('noindex') ? 'noindex' : 'index';
  }
  return null;
}

// WP Super Cache 꼬리표 시각(서버 KST)이 지금보다 2분 넘게 이르면 캐시본으로 본다
export function staleCache(html, now = Date.now()) {
  const m = html.match(/Cached page generated by WP-Super-Cache on (\d{4}-\d\d-\d\d) (\d\d:\d\d:\d\d)/);
  return !!m && now - Date.parse(`${m[1]}T${m[2]}+09:00`) > 120e3;
}

// 실제 페이지. 오류면 다시 두드리지 않는다
async function live(link) {
  try {
    const r = await fetch(`${link}${link.includes('?') ? '&' : '?'}nocache=${Date.now()}`, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(15e3) });
    if (!r.ok) return { err: `HTTP ${r.status}` };
    const html = await r.text();
    return { robots: robotsOf(html), cached: staleCache(html) };
  } catch (e) { return { err: e.name === 'TimeoutError' ? '시간 초과' : e.message }; }
}
const show = (v) => v.err ? `✗ ${v.err}` : `${v.robots ?? '메타 없음'}${v.cached ? ' (캐시일 수 있음)' : ''}`;

async function published() {
  const { wp } = await import('./wp.mjs');
  const out = [];
  for (let page = 1; ; page++) {
    let rows;
    try { rows = await wp(`posts?status=publish&per_page=100&page=${page}&_fields=id,slug,link,type`); } catch (e) { if (page > 1 && /HTTP 400/.test(e.message)) break; throw e; }
    out.push(...rows);
    if (rows.length < 100) break;
  }
  return out;
}

async function targets(a) {
  const all = await published(), list = pick(all);
  const only = a.includes('--only') ? a[a.indexOf('--only') + 1]?.split(',').filter(Boolean) : null;
  if (!only) return { all, list };
  const miss = only.filter((s) => !list.some((p) => p.slug === s));
  if (miss.length) { console.log(`대상(공개된 apt- 글)에 없음: ${miss.join(', ')}`); process.exit(4); }
  return { all, list: list.filter((p) => only.includes(p.slug)) };
}

async function setRobots(list, state) {
  const { wp } = await import('./wp.mjs');
  const book = JSON.parse(await readFile(FILE, 'utf8').catch(() => '{}'));
  let ok = 0, bad = 0, streak = 0;
  for (const [i, p] of list.entries()) {
    if (i) await sleep(GAP);
    let line;
    try {
      const res = await wp('../../rankmath/v1/updateMeta', { method: 'POST', body: { objectType: 'post', objectID: p.id, meta: { rank_math_robots: [state] } } });
      console.log(`  응답 ${p.slug}: ${JSON.stringify(res)?.slice(0, 200)}`);
      book[p.slug] = { id: p.id, state, at: kst() };
      await writeFile(FILE, JSON.stringify(book, null, 1));
      await sleep(GAP);
      const v = await live(p.link);
      line = v.robots === state ? `✓ ${state} ${p.slug}` : `✗ ${p.slug} 페이지 robots ${v.err ? v.err : `${v.robots ?? '메타 없음'} — 캐시일 수 있음`}`;
    } catch (e) { line = `✗ ${p.slug} 보내기 실패: ${e.message}`; }
    console.log(line);
    if (line.startsWith('✓')) { ok++; streak = 0; } else { bad++; streak++; }
    if (streak >= STOP) { console.log(`실패가 ${STOP}번 이어져 멈춤(남은 ${list.length - i - 1}편은 손대지 않음)`); break; }
  }
  const { purge } = await import('./site.mjs');
  console.log('캐시 비우기', (await purge().catch(() => false)) ? '✓' : '✗');
  console.log(`끝: 성공 ${ok}편 · 실패 ${bad}편 (기록 data/zip_noindex.json)`);
  process.exitCode = bad ? 2 : 0;
}

async function verify(list, all) {
  const n = { noindex: 0, index: 0, none: 0, err: 0 };
  for (const [i, p] of list.entries()) {
    if (i) await sleep(GAP);
    const v = await live(p.link);
    n[v.err ? 'err' : v.robots ?? 'none']++;
    console.log(`  ${p.slug} ${show(v)}`);
  }
  console.log(`시세 비교 글 ${list.length}편: noindex ${n.noindex} · index ${n.index} · 메타 없음 ${n.none} · 오류 ${n.err}`);
  await sleep(GAP);
  try {
    const r = await fetch(`https://auleezip.com/post-sitemap.xml?nocache=${Date.now()}`, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(15e3) });
    const locs = r.ok ? (await r.text()).match(/<loc>[^<]*<\/loc>/g) || [] : [];
    console.log(r.ok ? `사이트맵 post-sitemap.xml: 주소 ${locs.length}개 중 apt- ${locs.filter((l) => /\/apt-/.test(l)).length}개` : `사이트맵 ✗ HTTP ${r.status}`);
  } catch (e) { console.log(`사이트맵 ✗ ${e.message}`); }
  for (const p of all.filter((x) => x.slug.startsWith('deep-')).slice(0, 3)) {
    await sleep(GAP);
    console.log(`  심층 분석 ${p.slug} ${show(await live(p.link))}`);
  }
}

if (process.argv[1]?.endsWith('noindex.mjs')) {
  const a = process.argv;
  if (a.includes('--check')) {
    const assert = (await import('node:assert/strict')).default;
    const P = (slug, type) => ({ id: 1, slug, link: `https://auleezip.com/${slug}/`, ...(type && { type }) });
    assert.deepEqual(pick([P('apt-2026000502'), P('deep-2026910299'), P('apt-1', 'page'), P('method'), P('xapt-1'), P('apt-2', 'post')]).map((p) => p.slug), ['apt-2026000502', 'apt-2']);
    assert.equal(robotsOf('<meta name="robots" content="follow, noindex"/>'), 'noindex');
    assert.equal(robotsOf('<meta name="robots" content="follow, index, max-snippet:-1, max-video-preview:-1, max-image-preview:large"/>'), 'index');
    assert.equal(robotsOf('<meta content="noindex, nofollow" name="robots">'), 'noindex');
    assert.equal(robotsOf("<meta name='robots' content='index,nofollow'>"), 'index');
    assert.equal(robotsOf('<meta name="googlebot" content="noindex"><title>x</title>'), null);
    assert.equal(robotsOf('<html></html>'), null);
    const now = Date.parse('2026-11-16T02:47:00+09:00');
    assert.equal(staleCache('<!-- Cached page generated by WP-Super-Cache on 2026-11-16 02:46:42 -->', now), false);
    assert.equal(staleCache('<!-- Cached page generated by WP-Super-Cache on 2026-11-16 01:00:00 -->', now), true);
    assert.equal(staleCache('<p>no tag</p>', now), false);
    console.log('noindex 점검 통과');
  } else {
    const { all, list } = await targets(a);
    if (a.includes('--go')) await setRobots(list, 'noindex');
    else if (a.includes('--undo')) await setRobots(list, 'index');
    else if (a.includes('--verify')) await verify(list, all);
    else {
      console.log(`공개 글 ${all.length}편 중 시세 비교(apt-) ${list.length}편 — 계획만, 쓰기 없음`);
      for (const [i, p] of list.entries()) {
        if (!a.includes('--live')) { console.log(`  ${p.slug} (id ${p.id})`); continue; }
        if (i) await sleep(GAP);
        console.log(`  ${p.slug} (id ${p.id}) ${show(await live(p.link))}`);
      }
      console.log('적용: node zip/noindex.mjs --go [--only apt-…]  되돌리기: --undo  확인: --verify');
    }
  }
}
